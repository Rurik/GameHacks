#!/usr/bin/env python3
import argparse
import datetime
import hashlib
import json
from pathlib import Path
import re
import shutil
import sys
import tempfile

NAME = 'PlayerQoL'
DEFAULTS = dict(SceneFadeFrames='0', EventFadeFrames='0', InstantDialogue='true',
                AnimationSpeed='2', EventFastForward4x='false', WalkKeyCode='118',
                SpeedKeyCode='117', HistoryKeyCode='72', HistoryLimit='200')

def digest(data):
    return hashlib.sha256(data).hexdigest()

def atomic(path, data):
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as f:
        temp = Path(f.name)
        f.write(data)
    try:
        temp.replace(path)
    finally:
        temp.unlink(missing_ok=True)

def root_at(path):
    candidates = [path, path/'www', path/'Contents/Resources/app.nw',
                  path/'Contents/Resources/app.nw/www']
    matches = [p for p in candidates if (p/'js/plugins.js').is_file() and
               (p/'js/rpg_core.js').is_file()]
    if len(matches) != 1:
        raise ValueError('Expected exactly one MV root with js/plugins.js and js/rpg_core.js. Pass www directly if needed.')
    root = matches[0].resolve()
    core = (root/'js/rpg_core.js').read_text(encoding='utf-8-sig')
    if not re.search(r'RPGMAKER_NAME\s*=\s*[\'"]MV[\'"]', core):
        raise ValueError('Could not verify RPG Maker MV; refusing this deployment.')
    return root

def install(args):
    root = root_at(args.game.resolve())
    registry = root/'js/plugins.js'
    text = registry.read_text(encoding='utf-8-sig')
    # Stock registry is JSON wrapped in a JS assignment.
    match = re.fullmatch(r'\s*(?://[^\n]*\n\s*)*var\s+\$plugins\s*=\s*(\[.*\])\s*;?\s*', text, re.S)
    if not match:
        raise ValueError('Custom plugins.js format; use manual installation. Nothing changed.')
    entries = json.loads(match.group(1))
    if not all(isinstance(e, dict) and isinstance(e.get('name'), str) for e in entries):
        raise ValueError('Invalid plugin registry.')
    old = [e for e in entries if e['name'].lower() == NAME.lower()]
    if len(old) > 1:
        raise ValueError('Duplicate PlayerQoL entries; resolve manually.')
    params = DEFAULTS.copy()
    if old:
        params.update(old[0].get('parameters', {}))
        # Migrate the original default away from MV's developer-tools key.
        if params.get('SpeedKeyCode') == '119':
            params['SpeedKeyCode'] = '117'
    for item in args.set:
        key, sep, value = item.partition('=')
        if not sep or key not in DEFAULTS:
            raise ValueError('Unknown setting: '+item)
        if key in ('InstantDialogue','EventFastForward4x'):
            if value not in ('true','false'): raise ValueError('Boolean must be true or false')
        else:
            n = int(value)
            lo, hi = (-1,600) if 'FadeFrames' in key else ((1,4) if key=='AnimationSpeed' else ((1,1000) if key=='HistoryLimit' else (1,255)))
            if not lo <= n <= hi: raise ValueError('Out-of-range setting: '+item)
        params[key] = value
    if len({params[k] for k in ('WalkKeyCode','SpeedKeyCode','HistoryKeyCode')}) != 3:
        raise ValueError('Hotkeys must be distinct.')
    entries = [e for e in entries if e['name'].lower()!=NAME.lower()]
    entries.append(dict(name=NAME,status=True,description='MV player quality of life v1.2',parameters=params))
    source = Path(__file__).with_name(NAME+'.js')
    changes = {registry: ('// Generated by PlayerQoL installer\nvar $plugins =\n'+json.dumps(entries,ensure_ascii=False,indent=2)+';\n').encode(),
               root/'js/plugins'/source.name: source.read_bytes()}
    for path in changes:
        if path.is_symlink() or not path.resolve().is_relative_to(root):
            raise ValueError('Refusing symlink/outside-root target: '+str(path))
    if args.dry_run:
        print('Validated. Would install LAST in:',root)
        print(json.dumps(params,indent=2)); return
    backup = root/'PlayerQoL-backups'/datetime.datetime.now().strftime('%Y%m%d-%H%M%S-%f')
    backup.mkdir(parents=True)
    manifest = dict(root=str(root), files=[])
    for i,(path,data) in enumerate(changes.items()):
        exists = path.exists()
        if exists: shutil.copy2(path,backup/str(i))
        manifest['files'].append(dict(path=str(path.relative_to(root)),backup=str(i) if exists else None,installed_sha256=digest(data)))
    (backup/'manifest.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
    try:
        for path,data in changes.items():
            path.parent.mkdir(parents=True,exist_ok=True); atomic(path,data)
    except Exception:
        for record in manifest['files']:
            path=root/record['path']
            if record['backup'] is None: path.unlink(missing_ok=True)
            else: atomic(path,(backup/record['backup']).read_bytes())
        raise
    print('Installed. Backup/restore folder:',backup)

def restore(folder):
    folder=folder.resolve()
    manifest=json.loads((folder/'manifest.json').read_text(encoding='utf-8'))
    root=Path(manifest['root']).resolve()
    planned=[]
    for record in manifest['files']:
        path=root/record['path']
        if path.is_symlink() or not path.resolve().is_relative_to(root): raise ValueError('Unsafe restore path')
        if not path.is_file() or digest(path.read_bytes())!=record['installed_sha256']:
            raise ValueError('File changed since installation; restore manually to avoid overwriting later edits: '+str(path))
        src=folder/record['backup'] if record['backup'] else None
        if src and (not src.resolve().is_relative_to(folder) or not src.is_file()): raise ValueError('Invalid backup')
        planned.append((path,src.read_bytes() if src else None))
    for path,data in planned:
        if data is None: path.unlink()
        else: atomic(path,data)
    print('Restored original plugin files. Saves were not modified.')

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    sub=parser.add_subparsers(dest='action',required=True)
    ins=sub.add_parser('install'); ins.add_argument('game',type=Path)
    ins.add_argument('--dry-run',action='store_true');ins.add_argument('--set',action='append',default=[],metavar='KEY=VALUE')
    res=sub.add_parser('restore');res.add_argument('backup',type=Path)
    args=parser.parse_args()
    try:
        if args.action=='install': install(args)
        else: restore(args.backup)
    except (ValueError,OSError,KeyError,TypeError) as e:
        print('Error:',e,file=sys.stderr);return 1
    return 0
if __name__=='__main__': sys.exit(main())
